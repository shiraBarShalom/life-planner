export function hashStr(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

export function quoteFor(settings, iso, offset = 0) {
  const custom = settings.customQuotes || [];
  const pool = [...custom, ...custom, ...QUOTES]; // personal quotes appear more often
  return pool[(hashStr(iso) + offset) % pool.length];
}

export function challengeFor(iso) {
  return CHALLENGES[hashStr('c' + iso) % CHALLENGES.length];
}
